def render(template: str, **values: str) -> str:
    """把模板里的 ``{name}`` 占位符替换为 ``values`` 中对应的值。

    Args:
        template: 含 ``{name}`` 占位符的提示词模板。
        **values: 占位符名到实际文本的映射；值会原样插入，不做转义。

    Returns:
        替换完成的提示词。未在 ``values`` 中出现的占位符保持原样。
    """
    result = template
    for name, value in values.items():
        result = result.replace("{" + name + "}", value)
    return result
